def create_styles() -> Dict[str, xlwt.XFStyle]:
    """Создание стилей для Excel."""
    # Стиль для заголовков
    font0 = xlwt.Font()
    font0.name = 'Century Gothic'
    font0.colour_index = 0
    font0.bold = True
    style0 = xlwt.XFStyle()
    style0.font = font0

    # Стиль для обычного текста
    font1 = xlwt.Font()
    font1.name = 'Century Gothic'
    font1.colour_index = 0
    style1 = xlwt.XFStyle()
    style1.font = font1

    return {'header': style0, 'normal': style1}


